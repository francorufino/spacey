export const destinationBusMap = spaceBuses.reduce((map, bus) => {
  bus.serves.forEach((destination) => {
    map[destination.replace(/^The /, "")] = bus;
    map[destination] = bus;
  });
  return map;
}, {});

export const getBusForDestination = (destinationName) => destinationBusMap[destinationName] || destinationBusMap[destinationName.replace(/^The /, "")];
export const getSpaceBus = (slug) => spaceBuses.find((bus) => bus.slug === slug);
